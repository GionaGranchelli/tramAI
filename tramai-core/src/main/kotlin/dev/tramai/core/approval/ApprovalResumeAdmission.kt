package dev.tramai.core.approval

import dev.tramai.core.identity.GovernedRunIdentity
import dev.tramai.core.identity.WorkflowCheckpointBinding
import dev.tramai.core.observation.secondary.ExperimentalTramaiInternalApi
import java.util.concurrent.atomic.AtomicBoolean

/**
 * One approval-resume admission request (E9).
 *
 * Everything the authority needs and nothing it could guess: the approval, the tool being resumed, the governed run,
 * and the checkpoint row that is claimed to own it. The binding is data supplied by the suspension record, never
 * derived inside the authority.
 *
 * ### Copy Semantics & Stable ABI Contract
 * To preserve strict binary compatibility on this `stable` module for callers compiled against TramAI <= 0.7.6,
 * the primary constructor retains its historical 4-argument signature:
 * `(approvalId, toolName, runIdentity, checkpointBinding)`.
 *
 * Consequently, the synthetic 4-argument `copy()` method generated by the Kotlin compiler delegates to that
 * primary constructor and **does not** retain [continuationVersion] (it resets it to `0L`).
 *
 * For versioned requests, callers MUST use:
 * - [copyWithContinuationVersion] to copy while preserving [continuationVersion] by default; or
 * - the 5-argument [copy] overload passing [continuationVersion] explicitly; or
 * - [withContinuationVersion] to update only the version.
 */
data class ApprovalResumeAdmissionRequest(
    val approvalId: String,
    val toolName: String,
    val runIdentity: GovernedRunIdentity,
    val checkpointBinding: WorkflowCheckpointBinding,
) {
    var continuationVersion: Long = 0L
        private set

    constructor(
        approvalId: String,
        toolName: String,
        runIdentity: GovernedRunIdentity,
        checkpointBinding: WorkflowCheckpointBinding,
        continuationVersion: Long,
    ) : this(approvalId, toolName, runIdentity, checkpointBinding) {
        this.continuationVersion = continuationVersion
    }

    /**
     * Copy this request while preserving [continuationVersion] by default.
     * Use this method instead of the synthetic 4-argument [copy] when copying a versioned request.
     */
    fun copyWithContinuationVersion(
        approvalId: String = this.approvalId,
        toolName: String = this.toolName,
        runIdentity: GovernedRunIdentity = this.runIdentity,
        checkpointBinding: WorkflowCheckpointBinding = this.checkpointBinding,
        continuationVersion: Long = this.continuationVersion,
    ): ApprovalResumeAdmissionRequest =
        ApprovalResumeAdmissionRequest(
            approvalId = approvalId,
            toolName = toolName,
            runIdentity = runIdentity,
            checkpointBinding = checkpointBinding,
            continuationVersion = continuationVersion,
        )

    /**
     * Create a copy of this request with the given [continuationVersion].
     */
    fun withContinuationVersion(continuationVersion: Long): ApprovalResumeAdmissionRequest =
        copyWithContinuationVersion(continuationVersion = continuationVersion)

    fun copy(
        approvalId: String = this.approvalId,
        toolName: String = this.toolName,
        runIdentity: GovernedRunIdentity = this.runIdentity,
        checkpointBinding: WorkflowCheckpointBinding = this.checkpointBinding,
        continuationVersion: Long,
    ): ApprovalResumeAdmissionRequest =
        ApprovalResumeAdmissionRequest(
            approvalId,
            toolName,
            runIdentity,
            checkpointBinding,
            continuationVersion,
        )

    override fun equals(other: Any?): Boolean {
        if (this === other) return true
        if (other !is ApprovalResumeAdmissionRequest) return false
        return approvalId == other.approvalId &&
            toolName == other.toolName &&
            runIdentity == other.runIdentity &&
            checkpointBinding == other.checkpointBinding &&
            continuationVersion == other.continuationVersion
    }

    override fun hashCode(): Int {
        var result = approvalId.hashCode()
        result = 31 * result + toolName.hashCode()
        result = 31 * result + runIdentity.hashCode()
        result = 31 * result + checkpointBinding.hashCode()
        result = 31 * result + continuationVersion.hashCode()
        return result
    }

    override fun toString(): String =
        "ApprovalResumeAdmissionRequest(approvalId=$approvalId, toolName=$toolName, " +
            "runIdentity=$runIdentity, checkpointBinding=$checkpointBinding, continuationVersion=$continuationVersion)"
}

/**
 * Fixed diagnostic categories for durable evidence.
 * Raw exception messages, sensitive paths, or arbitrary strings must NEVER enter durable evidence.
 */
enum class WorkflowEvidenceDiagnosticCategory {
    TOOL_EXECUTION_FAILED,
    TOOL_EXECUTION_TIMEOUT,
    TOOL_EXECUTION_CANCELLED,
    PERSISTENCE_FAILED,
    RECONCILIATION_REQUIRED,
}

/**
 * Callback handle for recording evidence during approval resume execution.
 * Passed via [ApprovalResumePermit] to bridge orchestration evidence storage
 * across the engine execution boundary without violating module dependencies.
 */
interface ApprovalResumeEvidenceHandle {
    suspend fun recordDispatched()

    suspend fun recordCompleted()

    suspend fun recordUncertain(
        error: Throwable,
        category: WorkflowEvidenceDiagnosticCategory,
    )
}

/**
 * Workflow-bound approval continuation admission (E9) as a capability distinct from approval authorization.
 *
 * **Approval is not permission to bypass authoritative workflow cancellation.** The approval decision says a human
 * allowed this tool call; this capability says the owning workflow may still execute anything at all. Both must hold
 * before a resumed invocation is dispatched, and neither implies the other.
 *
 * **Scope, stated narrowly.** A grant means *this resumed executor invocation was admitted by its owning workflow's
 * durable authority*. It does not establish that any effect inside the executor happened, and it says nothing about a
 * governed engine invocation that no workflow owns — a standalone engine user has a [GovernedRunIdentity] without a
 * checkpoint, and no workflow-level cancellation guarantee applies to it.
 *
 * Implementations live where the durable authority lives (the workflow module), and are injected at composition time;
 * the engine only consumes this interface.
 */
fun interface ApprovalResumeAdmission {
    /**
     * Take a fresh, durable, single-use grant for one resumed invocation.
     *
     * @throws dev.tramai.core.exception.ApprovalResumeAdmissionRefusedException when the authority refuses.
     */
    suspend fun admitResume(request: ApprovalResumeAdmissionRequest): ApprovalResumePermit
}

/**
 * One durable grant for one resumed approval invocation, consumable exactly once.
 *
 * [admissionSequence] is the durable part of the identity: it is the only component the authority issues. Consumption
 * is local to this attempt and deliberately not durable — a worker that dies after the invocation admits again on
 * restart, which must never be read as exactly-once execution.
 */
@ExperimentalTramaiInternalApi
class ApprovalResumePermit(
    val approvalId: String,
    val checkpointBinding: WorkflowCheckpointBinding,
    val admissionSequence: Long,
    val checkpointGeneration: String? = null,
    val evidenceHandle: ApprovalResumeEvidenceHandle? = null,
) {
    private val consumed = AtomicBoolean(false)

    // Retained 3-parameter constructor for binary compatibility
    constructor(
        approvalId: String,
        checkpointBinding: WorkflowCheckpointBinding,
        admissionSequence: Long,
    ) : this(approvalId, checkpointBinding, admissionSequence, null, null)

    /**
     * Consume the permit: true exactly once. A second call is a programming error and fails rather than re-dispatching,
     * because one permit authorizes at most one resumed invocation.
     */
    fun tryConsume(): Boolean {
        check(!consumed.getAndSet(true)) {
            "approval resume permit for '${checkpointBinding.workflowName}/${checkpointBinding.workflowId}' " +
                "approval '$approvalId' (admission $admissionSequence) was already consumed; " +
                "one permit authorizes at most one resumed invocation"
        }
        return true
    }
}
