    // --- 3. Corrupt checkpoint secret payload reaches observer only ---

    @Test
    fun `corrupt checkpoint containing secret payload reaches observer but not public exception`() {
        runBlocking {
            val observer = RecordingPersistenceObserver()
            val store = FileWorkflowCheckpointStore(tempDir)
            store.persistenceFailureDiagnosticObserver = observer
            // Write a checkpoint file whose recovery state decodes to garbage carrying the secret.
            val checkpointDir = tempDir.resolve("wf").resolve("run-1").toFile()
            checkpointDir.mkdirs()
            Files.writeString(
                tempDir.resolve("wf").resolve("run-1").resolve("checkpoint.properties"),
                "workflowName=wf\nworkflowId=run-1\nnextStepIndex=0\nstepExecutions=0\nstatePayloadBase64=c3RhdGU=\nrevision=1\nrecoveryState=${base64Encode(SECRET_PAYLOAD)}\n",
            )

            val thrown = catchThrowable {
                runBlocking { store.load("wf", "run-1") }
            }

            assertThat(thrown).isInstanceOf(WorkflowCheckpointCorruptionException::class.java)
            assertNoSecret(thrown, SECRET_PAYLOAD)
            assertThat(observer.events).hasSize(1)
            assertThat(observer.events.single().failureCode).isEqualTo(PersistenceFailureCode.CORRUPTED_DATA)
        }
    }

    // --- 4. Corrupt step-attempt record secret value reaches observer only ---

    @Test
    fun `corrupt step attempt record containing secret value reaches observer but not public exception`() {
        runBlocking {
            val observer = RecordingPersistenceObserver()
            val store = FileStepAttemptRecordStore.forTest(tempDir, realAtomicFileWriter)
            store.persistenceFailureDiagnosticObserver = observer
            // Seed one record then corrupt its status to an unknown value carrying the secret.
            val record = minimalAttempt()
            store.recordStepAttempt(record)
            val attemptPath = tempDir
                .resolve(base64UrlEncodeNoPadding(record.runId))
                .resolve(base64UrlEncodeNoPadding(record.stepName))
                .resolve(base64UrlEncodeNoPadding(record.attemptId) + ".attempt.properties")
            val raw = Files.readString(attemptPath)
            Files.writeString(attemptPath, raw.replace("status=STARTED", "status=$SECRET_VALUE"))

            val thrown = catchThrowable {
                runBlocking { store.listStepAttempts(record.runId) }
            }

            assertThat(thrown).isInstanceOf(StepAttemptRecordCorruptionException::class.java)
            assertNoSecret(thrown, SECRET_VALUE)
            assertThat(observer.events).hasSize(1)
            assertThat(observer.events.single().failureCode).isEqualTo(PersistenceFailureCode.CORRUPTED_DATA)
        }
    }

    // --- 5. Untrusted caller-constructed domain exception is re-sanitized ---

    @Test
    fun `caller constructed untrusted domain exception is re sanitized`() {
        runBlocking {
            val observer = RecordingPersistenceObserver()
            val untrusted = WorkflowCheckpointCorruptionException("password=fixture-sentinel-7f3c")

            val thrown = catchThrowable {
                runBlocking {
                    persistenceBoundary(
                        PersistenceResourceKind.CHECKPOINT,
                        PersistenceOperation.LOAD,
                        observer,
                    ) { throw untrusted }
                }
            }

            assertThat(thrown).isInstanceOf(WorkflowCheckpointCorruptionException::class.java)
            assertThat(thrown).isNotSameAs(untrusted)
            assertNoSecret(thrown, "password=")
            assertNoSecret(thrown, "fixture-sentinel-7f3c")
            assertThat(observer.events).hasSize(1)
            assertThat(observer.events.single().failure).isSameAs(untrusted)
        }
    }

