/**
 * Adversarial leak tests for the persistence safe-failure boundary (PR #225).
 *
 * The invariant: filesystem paths, SQL text, persisted payloads, and arbitrary
 * exception messages never cross from persistence internals into public
 * exceptions, ordinary observers, or logs. The original failure reaches only
 * [PersistenceFailureDiagnosticObserver]; cancellation stays cancellation.
 *
 * Secret fixtures use the value `fixture-sentinel-7f3c` (GitGuardian-safe:
 * no credential-shaped keys). Assertions scan message + cause + EVERY
 * suppressed throwable + observer events.
 */
class PersistenceSafeFailureBoundaryTest {

    @TempDir
    lateinit var tempDir: Path

    private companion object {
        const val SECRET_SQL = "UPDATE tramai_workflow SET state_payload = 'fixture-sentinel-7f3c'"
        const val SECRET_PATH = "/home/customer/acme/private/fixture-sentinel-7f3c/workflow"
        const val SECRET_PAYLOAD = "fixture-sentinel-7f3c-persisted-state"
        const val SECRET_VALUE = "fixture-sentinel-7f3c-value"
    }

    private class RecordingPersistenceObserver : PersistenceFailureDiagnosticObserver {
        val events = mutableListOf<PersistenceFailureDiagnosticEvent>()
        var throwAfterRecording: Throwable? = null
        var throwFakeCancellation: Boolean = false

        override suspend fun onFailure(event: PersistenceFailureDiagnosticEvent) {
            events += event
            if (throwFakeCancellation) throw CancellationException("synthetic observer cancellation")
            throwAfterRecording?.let { throw it }
        }
    }

    private fun assertNoSecret(t: Throwable?, secret: String, seen: MutableSet<Throwable> = mutableSetOf()) {
        if (t == null || !seen.add(t)) return
        assertThat(t.message).doesNotContain(secret)
        assertThat(t.toString()).doesNotContain(secret)
        assertNoSecret(t.cause, secret, seen)
        t.suppressed.forEach { assertNoSecret(it, secret, seen) }
    }

