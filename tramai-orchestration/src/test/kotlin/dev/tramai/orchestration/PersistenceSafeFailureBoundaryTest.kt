    // --- 1. JDBC secret SQL reaches observer only ---

    @Test
    fun `raw jdbc exception containing secret sql reaches observer but not public exception`() {
        runBlocking {
            val observer = RecordingPersistenceObserver()
            val store = JdbcWorkflowCheckpointStore(SeededSqlDataSource(SQLException(SECRET_SQL)))
            store.persistenceFailureDiagnosticObserver = observer

            val thrown = catchThrowable {
                runBlocking { store.save(testCheckpoint()) }
            }

            assertThat(thrown).isInstanceOf(WorkflowPersistenceFailureException::class.java)
            assertNoSecret(thrown, SECRET_SQL)
            assertThat(observer.events).hasSize(1)
            val event = observer.events.single()
            assertThat(event.resourceKind).isEqualTo(PersistenceResourceKind.CHECKPOINT)
            assertThat(event.operation).isEqualTo(PersistenceOperation.SAVE)
            assertThat(event.failureCode).isEqualTo(PersistenceFailureCode.WRITE_FAILED)
            assertThat(event.failure.message).contains(SECRET_SQL)
        }
    }

