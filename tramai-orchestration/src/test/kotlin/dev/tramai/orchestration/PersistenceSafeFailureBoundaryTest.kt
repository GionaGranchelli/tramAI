/**
 * Adversarial leak tests for the persistence safe-failure boundary (PR #225).
 *
 * The invariant: filesystem paths, SQL text, persisted payloads, and arbitrary
 * exception messages never cross from persistence internals into public
 * exceptions, ordinary observers, or logs. The original failure reaches only
 * [PersistenceFailureDiagnosticObserver]; cancellation stays cancellation.
 *
 * Secret fixtures use the value `fixture-sentinel-7f3c` (GitGuardian-safe:
 * no credential-shaped keys). Assertions scan message + cause + EVERY
 * suppressed throwable + observer events.
 */
