    // --- 9. Genuine parent cancellation stays primary, emits no diagnostic ---

    @Test
    fun `genuine parent cancellation remains primary and emits no diagnostic`() {
        runBlocking {
            val observer = RecordingPersistenceObserver()
            val entered = CompletableDeferred<Unit>()
            val release = CompletableDeferred<Unit>()

            val outer = CoroutineScope(Job())
            val outcome = CompletableDeferred<Throwable?>()
            outer.launch {
                try {
                    persistenceBoundary(
                        PersistenceResourceKind.CHECKPOINT,
                        PersistenceOperation.SAVE,
                        observer,
                    ) {
                        entered.complete(Unit)
                        release.await()
                        Unit
                    }
                    outcome.complete(null)
                } catch (t: Throwable) {
                    outcome.complete(t)
                }
            }
            entered.await()
            outer.coroutineContext[Job]!!.cancel()
            release.complete(Unit)
            val terminal = withTimeout(5_000) { outcome.await() }
            assertThat(terminal).isInstanceOf(CancellationException::class.java)
            assertThat(observer.events).isEmpty()
        }
    }

