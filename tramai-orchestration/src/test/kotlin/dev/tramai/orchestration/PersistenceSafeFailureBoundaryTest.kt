    private class RecordingPersistenceObserver : PersistenceFailureDiagnosticObserver {
        val events = mutableListOf<PersistenceFailureDiagnosticEvent>()
        var throwAfterRecording: Throwable? = null
        var throwFakeCancellation: Boolean = false

        override suspend fun onFailure(event: PersistenceFailureDiagnosticEvent) {
            events += event
            if (throwFakeCancellation) throw CancellationException("synthetic observer cancellation")
            throwAfterRecording?.let { throw it }
        }
    }

    private fun assertNoSecret(t: Throwable?, secret: String, seen: MutableSet<Throwable> = mutableSetOf()) {
        if (t == null || !seen.add(t)) return
        assertThat(t.message).doesNotContain(secret)
        assertThat(t.toString()).doesNotContain(secret)
        assertNoSecret(t.cause, secret, seen)
        t.suppressed.forEach { assertNoSecret(it, secret, seen) }
    }

