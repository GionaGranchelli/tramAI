    // --- 12. Worker onPollFailed receives only the safe failure ---

    @Test
    fun `worker onPollFailed receives only safe failure`() {
        val pollFailures = mutableListOf<Throwable>()
        val workerObserver = object : TramaiWorkerObserver {
            override fun onPollFailed(workerId: String, error: Throwable) {
                pollFailures += error
            }
        }
        val failingCatalog = FailingCheckpointCatalog(SQLException(SECRET_SQL))
        val checkpointStore = InMemoryWorkflowCheckpointStore()

        val worker = TramaiWorker(
            config = WorkerConfig(
                workerId = "worker-secret-test",
                poolName = "tests",
                pollIntervalMillis = 20,
                leaseDurationMillis = 200,
                drainTimeoutMillis = 1_000,
                partitionEnabled = false,
                workerCount = 1,
            ),
            leaseStore = InMemoryWorkflowLeaseStore(),
            checkpointStore = checkpointStore,
            checkpointCatalog = failingCatalog,
            stepAttemptStore = checkpointStore,
            workflowRegistry = emptyMap(),
            observability = workerObserver,
        )
        runBlocking {
            worker.start()
            try {
                withTimeout(5_000) {
                    while (pollFailures.isEmpty() && currentCoroutineContext().isActive) delay(20)
                }
            } finally {
                worker.shutdown()
            }
        }

        assertThat(pollFailures).isNotEmpty()
        pollFailures.forEach { failure ->
            assertThat(failure).isInstanceOf(WorkflowPersistenceFailureException::class.java)
            assertNoSecret(failure, SECRET_SQL)
        }
    }

